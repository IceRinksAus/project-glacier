"use client";

import { PackageCheck, Printer } from "lucide-react";
import { use, useEffect, useState } from "react";

import {
  PublicProductCollectionPassPresentation,
  publicBookingService,
} from "@/services/public-booking.service";

export default function ProductCollectionPassPage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = use(params);
  const [pass, setPass] =
    useState<PublicProductCollectionPassPresentation | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    let active = true;
    publicBookingService
      .getProductCollectionPass(token)
      .then((result) => {
        if (active) setPass(result);
      })
      .catch(() => {
        if (active) setError("This Product Collection Pass is not available.");
      });
    return () => {
      active = false;
    };
  }, [token]);

  return (
    <main className="min-h-screen bg-slate-100 px-4 py-10 text-slate-950 print:bg-white print:p-0">
      <section className="mx-auto max-w-xl rounded-3xl border bg-white p-6 shadow-sm print:max-w-none print:rounded-none print:shadow-none sm:p-9">
        {error ? <p role="alert">{error}</p> : null}
        {!pass && !error ? <p>Loading Product Collection Pass…</p> : null}
        {pass ? (
          <>
            <PackageCheck className="size-12 text-cyan-700" />
            <p className="mt-5 text-sm font-semibold uppercase tracking-widest text-cyan-800">
              Product Collection Pass
            </p>
            <h1 className="mt-2 text-3xl font-bold">
              {pass.productName}
              {pass.unitNumber && pass.unitCount
                ? ` ${pass.unitNumber} of ${pass.unitCount}`
                : ` × ${pass.quantity}`}
            </h1>
            {pass.variantName ? (
              <p className="mt-2 text-slate-600">{pass.variantName}</p>
            ) : null}
            <dl className="mt-6 grid gap-3 rounded-2xl bg-slate-50 p-5 text-sm">
              <div>
                <dt className="text-slate-500">Event</dt>
                <dd className="font-semibold">{pass.event.name}</dd>
              </div>
              {pass.session ? (
                <div>
                  <dt className="text-slate-500">Session</dt>
                  <dd className="font-semibold">{pass.session.name}</dd>
                </div>
              ) : null}
              <div>
                <dt className="text-slate-500">Booking</dt>
                <dd className="font-mono">{pass.bookingNumber}</dd>
              </div>
              <div>
                <dt className="text-slate-500">Pass</dt>
                <dd className="font-mono">{pass.passNumber}</dd>
              </div>
              {pass.unitNumber && pass.unitCount ? (
                <div>
                  <dt className="text-slate-500">Collection unit</dt>
                  <dd className="font-semibold">
                    {pass.unitNumber} of {pass.unitCount}
                  </dd>
                </div>
              ) : null}
              <div>
                <dt className="text-slate-500">Status</dt>
                <dd className="font-semibold">{pass.status}</dd>
              </div>
            </dl>
            {pass.status === "ACTIVE" ? (
              // eslint-disable-next-line @next/next/no-img-element -- authenticated token QR is generated by the Glacier API.
              <img
                src={publicBookingService.productCollectionPassQrUrl(token)}
                alt={`QR code for ${pass.productName} collection`}
                className="mx-auto mt-7 size-72 max-w-full"
              />
            ) : null}
            <p className="mt-6 rounded-xl border border-amber-200 bg-amber-50 p-4 text-sm font-semibold text-amber-950">
              This pass is for Product collection only. It does not grant rink
              entry.
            </p>
            <button
              type="button"
              onClick={() => window.print()}
              className="mt-6 inline-flex min-h-12 w-full items-center justify-center gap-2 rounded-xl bg-slate-950 px-5 font-bold text-white print:hidden"
            >
              <Printer className="size-5" />
              Print / Save PDF
            </button>
          </>
        ) : null}
      </section>
    </main>
  );
}
